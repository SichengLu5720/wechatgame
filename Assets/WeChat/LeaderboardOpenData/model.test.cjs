const assert = require('node:assert/strict');
const m = require('./model');
const rec = (count, time, id = 1) => ({version: 1, completedCount: count, achievedAtMs: time, marker: id.toString(16).padStart(32, '0')});
const user = r => ({nickname: 'fixture', avatarUrl: '', KVDataList: [{key: m.KEY, value: JSON.stringify(r)}]});
assert.deepEqual(m.merge(rec(10, 100), rec(9, 200)), rec(10, 100));
assert.deepEqual(m.merge(rec(10, 100), rec(10, 50)), rec(10, 100));
assert.deepEqual(m.merge(rec(10, 100), rec(11, 50, 2)), rec(11, 101));
assert.throws(() => m.parse([{key: m.KEY, value: '{broken'}]));
assert.throws(() => m.parse(null));
assert.throws(() => m.parse([{key: m.KEY, value: JSON.stringify(rec(21, 100))}]));
assert.equal(m.parse([]), null);
assert.throws(() => m.merge(rec(10, Number.MAX_SAFE_INTEGER), rec(11, 100)));
const records = [rec(6, 200, 1), rec(20, 300, 2), rec(6, 100, 3), rec(18, 200, 4), rec(18, 100, 5), rec(14, 200, 6), rec(14, 100, 7)];
const board = m.snapshot(records.map(user), records[0]);
assert.deepEqual(board.rows.map(x => x.record.marker), [2, 5, 4, 7, 6, 3, 1].map(x => rec(0, 1, x).marker));
assert.equal(board.self.rank, 7); assert.equal(board.rows[6], board.self);
assert.equal(m.snapshot([], rec(0, 1)).self.rank, 1);
assert.equal(m.snapshot([], rec(0, 1)).empty, true);
assert.equal(m.snapshot([user(rec(5, 1)), user(rec(5, 1))], rec(5, 1)).self, null);
assert.equal(m.snapshot([{KVDataList: [{key: m.KEY, value: 'broken'}]}, user(rec(5, 1))], rec(5, 1)).rows.length, 1);
console.log('LEADERBOARD MODEL PASS: merge, rollback clock, ties, malformed records, self identity, empty, duplicate identity');
